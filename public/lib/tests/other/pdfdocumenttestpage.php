use Com\Tecnick\Pdf\PdfConformance;

require(__DIR__ . '/../../../config.php');
require_once($CFG->libdir . '/filelib.php');

require_login();
$context = context_system::instance();
require_capability('moodle/site:config', $context);

$getpdf = optional_param('getpdf', 0, PARAM_INT);
$mode = optional_param('mode', 'pdfua1', PARAM_ALPHANUM);
$font = optional_param('font', '', PARAM_ALPHANUMEXT);

// Only the two modes offered below. The untagged one is a baseline for comparison.
$tagged = $mode !== 'none';
$conformance = $tagged ? PdfConformance::Pdfua1 : PdfConformance::None;
$modename = $tagged ? 'PDF/UA-1' : 'untagged';

// The content of this page and of the PDF it generates is fixed English text, so both have to declare
// themselves as English whatever the admin's own language is. Otherwise a non-English site would
// produce a test document whose /Lang does not match its content.
//
// force_current_language() stores the language in the session rather than for this request alone,
// so it has to be put back before the request ends, or every later page would be in English too.
$previouslang = force_current_language('en');

if ($getpdf) {
    try {
        $doc = new \core\pdf\document(mode: $conformance);
        if ($font !== '') {
            $doc->set_default_font($font);
        }

        $doc->setTitle("Moodle PDF library test ({$modename})");
        $doc->setSubject('Generated by lib/tests/other/pdfdocumenttestpage.php');
        $doc->setKeywords($tagged ? 'Moodle, PDF, PDF/UA, tagged' : 'Moodle, PDF, untagged');
        $doc->setPDFFilename('pdfdocumenttestpage.pdf');

        $doc->addPage();
        $region = $doc->page->getRegion();

        // Every element below should end up as a structure element in the tagged output. Headings must
        // not skip a level, tables need their header cells marked up as such, and the image needs alt
        // text, otherwise the document cannot pass a PDF/UA check. The untagged output has none of this,
        // so the text says what each element would be tagged as rather than claiming that it is.
        $tagnote = fn(string $tag): string => $tagged ? "tagged as {$tag}" : "untagged here, {$tag} in the tagged output";

        $content = '<h1>Moodle PDF library test (' . s($modename) . ')</h1>';
        if ($tagged) {
            $content .= '<p>Generated by <b>\core\pdf\document</b> as a tagged PDF/UA-1 document.</p>';
        } else {
            $content .= '<p>Generated by <b>\core\pdf\document</b> with tagging switched off, as a baseline for '
                . 'comparison. This file has no structure tree, so an accessibility checker should fail it.</p>';
        }

        $content .= '<h2>Environment</h2>';
        $content .= '<table>';
        $content .= '<caption>Current settings</caption>';
        $content .= '<tr><th scope="col">Setting</th><th scope="col">Value</th></tr>';
        $rows = [
            'Moodle release' => $CFG->release,
            'Conformance mode' => $modename,
            'K_PATH_CACHE' => defined('K_PATH_CACHE') ? constant('K_PATH_CACHE') : '(not defined)',
            'K_PATH_FONTS (TCPDF)' => defined('K_PATH_FONTS') ? constant('K_PATH_FONTS') : '(not defined)',
        ];
        foreach ($rows as $name => $value) {
            $content .= '<tr><td>' . s($name) . '</td><td>' . s((string) $value) . '</td></tr>';
        }
        $content .= '</table>';

        $content .= '<h2>Font directories searched</h2><ul>';
        foreach (\core\pdf\document::get_font_directories() as $dir) {
            $content .= '<li>' . s($dir) . '</li>';
        }
        $content .= '</ul>';

        $content .= '<h2>Text samples</h2>';
        $content .= '<p>Latin: The quick brown fox jumps over the lazy dog.</p>';
        // The German and French words carry their own language, which tagged output records as /Lang on
        // their structure elements.
        $content .= '<p>Accented: r&eacute;sum&eacute;, na&iuml;ve, <span lang="de">Stra&szlig;e</span>, '
            . '<span lang="fr">&ccedil;a va</span>.</p>';
        $content .= '<blockquote>A block quote, ' . $tagnote('BlockQuote') . '.</blockquote>';
        $content .= '<p>A <a href="' . $CFG->wwwroot . '">link to this site</a>, ' . $tagnote('Link') . '.</p>';

        $content .= '<h2>Image with alternative text</h2>';
        $content .= '<figure>';
        $content .= '<img src="' . $CFG->dirroot . '/pix/moodlelogo.png" alt="The Moodle logo" width="120" />';
        $content .= '<figcaption>The Moodle logo, ' . $tagnote('Figure with a Caption') . '.</figcaption>';
        $content .= '</figure>';

        $doc->addHTMLCell(
            width: $region['RW'] - 40,
            height: 0,
            posx: 20,
            posy: 20,
            html: $content,
        );

        $pdfcontent = $doc->getOutPDFString();
    } finally {
        // Restored before sending, because send_file() exits, and exit skips finally blocks.
        force_current_language($previouslang);
    }

    send_file($pdfcontent, 'pdfdocumenttestpage.pdf', 0, 0, true, true, 'application/pdf');
    exit();
}

try {
    $PAGE->set_url('/lib/tests/other/pdfdocumenttestpage.php');
    $PAGE->set_context($context);
    $PAGE->set_title('Tagged PDF library test');
    $PAGE->set_heading('Tagged PDF library test');

    echo $OUTPUT->header();
    echo $OUTPUT->heading('Generate a test PDF', 2);
    echo html_writer::tag('p', 'Generates a sample document with headings, a table, a list, a link and an '
        . 'image with alternative text, so that the structure of the output can be inspected.');
    $modes = [
        'pdfua1' => [
            'Download tagged PDF',
            'PDF/UA-1, which is what \core\pdf\document produces by default.',
        ],
        'none' => [
            'Download untagged PDF',
            'A baseline for comparison only, not a mode anything should be generating. Useful for seeing what '
                . 'the structure tree adds, and what it costs in file size.',
        ],
    ];
    echo html_writer::start_tag('dl');
    foreach ($modes as $value => [$label, $description]) {
        $url = new moodle_url($PAGE->url, ['getpdf' => 1, 'mode' => $value]);
        echo html_writer::tag('dt', html_writer::link($url, $label));
        echo html_writer::tag('dd', $description);
    }
    echo html_writer::end_tag('dl');
    echo $OUTPUT->footer();
} finally {
    force_current_language($previouslang);
}
